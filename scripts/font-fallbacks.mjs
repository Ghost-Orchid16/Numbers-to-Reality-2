#!/usr/bin/env node
/**
 * Generates metric-matched fallback @font-face rules for every typeface we ship.
 *
 * Reads the actual Fontsource woff2 files from node_modules with Capsize, compares them
 * with the metrics of a widely installed system face, and writes `size-adjust` +
 * ascent/descent/line-gap overrides so text set in the fallback occupies the same box as
 * the web font. Swapping fonts (font-display: swap) then causes no layout shift.
 *
 * Usage: npm run fonts:fallbacks   (output: src/styles/font-fallbacks.css — committed)
 */
import { createFontStack } from '@capsizecss/core'
import { entireMetricsCollection as system } from '@capsizecss/metrics/entireMetricsCollection'
import { fromFile } from '@capsizecss/unpack/fs'
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const nm = (p) => `${root}node_modules/${p}`

// Metric-compatible local faces: Liberation / Arimo / Tinos / Cousine share the metrics of
// Arial / Times New Roman / Courier New, so one set of overrides is valid for all of them.
const LOCALS = {
  arial: ['Arial', 'ArialMT', 'Liberation Sans', 'Arimo', 'Helvetica Neue', 'Helvetica'],
  timesNewRoman: ['Times New Roman', 'TimesNewRomanPSMT', 'Liberation Serif', 'Tinos', 'Times'],
  courierNew: ['Courier New', 'CourierNewPSMT', 'Liberation Mono', 'Cousine', 'Courier'],
}

/** family name as declared by Fontsource → latin file + fallback system face */
const FONTS = [
  { family: 'Manrope Variable', file: '@fontsource-variable/manrope/files/manrope-latin-wght-normal.woff2', base: 'arial' },
  { family: 'JetBrains Mono Variable', file: '@fontsource-variable/jetbrains-mono/files/jetbrains-mono-latin-wght-normal.woff2', base: 'courierNew' },
  { family: 'Unbounded Variable', file: '@fontsource-variable/unbounded/files/unbounded-latin-wght-normal.woff2', base: 'arial' },
  { family: 'Instrument Serif', file: '@fontsource/instrument-serif/files/instrument-serif-latin-400-italic.woff2', base: 'timesNewRoman', style: 'italic' },
  { family: 'Big Shoulders Stencil Variable', file: '@fontsource-variable/big-shoulders-stencil/files/big-shoulders-stencil-latin-opsz-normal.woff2', base: 'arial' },
  { family: 'Doto Variable', file: '@fontsource-variable/doto/files/doto-latin-rond-normal.woff2', base: 'courierNew' },
  { family: 'Archivo Variable', file: '@fontsource-variable/archivo/files/archivo-latin-wdth-italic.woff2', base: 'arial', style: 'italic' },
  { family: 'Syne Variable', file: '@fontsource-variable/syne/files/syne-latin-wght-normal.woff2', base: 'arial' },
  { family: 'Fraunces Variable', file: '@fontsource-variable/fraunces/files/fraunces-latin-soft-italic.woff2', base: 'timesNewRoman', style: 'italic' },
  { family: 'Bodoni Moda Variable', file: '@fontsource-variable/bodoni-moda/files/bodoni-moda-latin-opsz-normal.woff2', base: 'timesNewRoman' },
  { family: 'Tektur Variable', file: '@fontsource-variable/tektur/files/tektur-latin-wdth-normal.woff2', base: 'arial' },
  { family: 'Michroma', file: '@fontsource/michroma/files/michroma-latin-400-normal.woff2', base: 'arial' },
]

const pct = (v, fallback = '0%') => v ?? fallback
let css = `/* AUTO-GENERATED by scripts/font-fallbacks.mjs — do not edit by hand.
 * Metric-matched fallbacks: each "<Family> Fallback" face is a local system font scaled
 * (size-adjust) and re-boxed (ascent/descent/line-gap overrides) to match the web font. */\n`

for (const font of FONTS) {
  const metrics = await fromFile(nm(font.file))
  const fallback = system[font.base]
  const { fontFaces } = createFontStack([{ ...metrics, familyName: font.family }, fallback], {
    fontFaceFormat: 'styleObject',
  })
  const face = fontFaces[0]['@font-face']
  const src = LOCALS[font.base].map((n) => `local('${n}')`).join(', ')
  css += `
@font-face {
  font-family: '${font.family} Fallback';
  src: ${src};
  font-style: ${font.style ?? 'normal'};
  ascent-override: ${pct(face.ascentOverride)};
  descent-override: ${pct(face.descentOverride)};
  line-gap-override: ${pct(face.lineGapOverride)};
  size-adjust: ${pct(face.sizeAdjust, '100%')};
}
`
  console.log(`✓ ${font.family.padEnd(32)} → ${fallback.familyName.padEnd(16)} size-adjust ${face.sizeAdjust}`)
}

const out = `${root}src/styles/font-fallbacks.css`
await writeFile(out, css)
console.log(`\nwrote ${out}`)
